/**
 * @file Turns the parsed RIE-IEPR codelist into the structural model the
 * components render (plan 02).
 *
 * All functions are pure: they take the `CodelistResult` as their first
 * argument and never mutate it.
 *
 * Two rules from the plans are central here:
 *
 * 1. **Zichtbare types.** A concept with `isOnzichtbaar = true` is left out of
 *    the type selector, but its visible subtypes are kept (they become roots of
 *    the visible tree). Its eigenschappen are still inherited by those
 *    subtypes, because `getAncestors()` walks the full `broader` chain.
 *
 * 2. **Scoperegel.** An eigenschap applies to a type when its `relevantRiepr`
 *    contains that type or one of its ancestors. A composite has no
 *    `relevantRiepr` of its own: its scope is the union of its children's
 *    scopes, where a child without `relevantRiepr` inherits the parent's scope.
 *    An empty `relevantRiepr` therefore never means "all types".
 */

import type {
  CodelistResult,
  Concept,
  Eigenschap,
  SelectieOptie,
  StructuurType,
  Systeem,
  SysteemSleutel,
} from '../models/index.js'
import { CsorService } from './csor.js'
import volgorde from '../generated/csv-volgorde.json'

/** Dutch labels of the six systemen, in the order of the dropdown. */
const SYSTEMEN: { sleutel: SysteemSleutel; label: string }[] = [
  { sleutel: 'emissiepunt', label: 'Emissiepunt' },
  { sleutel: 'filter', label: 'Filter' },
  { sleutel: 'installatie', label: 'Installatie' },
  { sleutel: 'meetpunt', label: 'Meetpunt' },
  { sleutel: 'uitwisselpunt', label: 'Uitwisselpunt' },
  { sleutel: 'onttrekkingspunt', label: 'Onttrekkingspunt' },
]

/** CSV order per conceptscheme / collection, generated by `scripts/sync-codelist.mjs`. */
const CSV_VOLGORDE = volgorde as {
  schemes: Record<string, string[]>
  collections: Record<string, string[]>
}

/**
 * The six systemen with their two codelists.
 * @param result - Optional parsed codelist, used to fill in the scheme definitions.
 * @returns The systemen, in dropdown order.
 */
export function getSystemen(result?: CodelistResult): Systeem[] {
  return SYSTEMEN.map(({ sleutel, label }) => {
    const typeSchemaId = `conceptscheme:${sleutel}_type`
    const eigenschappenSchemaId = `conceptscheme:${sleutel}_eigenschappen`
    return {
      sleutel,
      label,
      typeSchemaId,
      eigenschappenSchemaId,
      definitie: result?.schemes.get(typeSchemaId)?.definition,
    }
  })
}

/**
 * Finds the systeem configuration for one key.
 * @param sleutel - The system key.
 * @param result - Optional parsed codelist for the definition.
 * @returns The systeem, or undefined for an unknown key.
 */
export function getSysteem(sleutel: string, result?: CodelistResult): Systeem | undefined {
  return getSystemen(result).find((systeem) => systeem.sleutel === sleutel)
}

/**
 * All concepten of a conceptscheme (including composite children), in CSV order.
 * @param result - The parsed codelist.
 * @param schemeId - The conceptscheme id.
 * @returns The concepten.
 */
function conceptenVanScheme(result: CodelistResult, schemeId: string): Concept[] {
  const concepten = [...result.concepts.values()].filter((concept) => concept.inScheme === schemeId)
  return sorteerOpCsvVolgorde(concepten, schemeId)
}

/**
 * Sorts concepten on their position in the source CSV (falling back to the
 * source order of the generated JSON-LD for unknown ids).
 * @param concepten - The concepten to sort.
 * @param schemeId - The conceptscheme the order belongs to.
 * @returns A new, sorted array.
 */
function sorteerOpCsvVolgorde(concepten: Concept[], schemeId: string): Concept[] {
  const order = CSV_VOLGORDE.schemes[schemeId] ?? []
  const index = new Map(order.map((id, position) => [id, position]))
  return [...concepten].sort((a, b) => {
    const positionA = index.get(a.id) ?? Number.MAX_SAFE_INTEGER
    const positionB = index.get(b.id) ?? Number.MAX_SAFE_INTEGER
    return positionA - positionB
  })
}

/**
 * The chain of parent types of a type, nearest parent first.
 * Includes invisible parents: they still define which eigenschappen apply.
 * @param result - The parsed codelist.
 * @param typeId - The type to walk up from.
 * @returns The ancestor ids (empty for a root type).
 */
export function getAncestors(result: CodelistResult, typeId: string): string[] {
  const ancestors: string[] = []
  const visited = new Set<string>([typeId])
  let current = result.concepts.get(typeId)?.broader

  while (current && !visited.has(current)) {
    ancestors.push(current)
    visited.add(current)
    current = result.concepts.get(current)?.broader
  }

  return ancestors
}

/**
 * The visible types of one systeem, in tree order (parent before child).
 * Invisible types are dropped; their visible children become roots.
 * @param result - The parsed codelist.
 * @param systeem - The system key or its `Systeem`.
 * @returns The visible types with their depth.
 */
export function getTypes(result: CodelistResult, systeem: SysteemSleutel | Systeem): StructuurType[] {
  const sleutel = typeof systeem === 'string' ? systeem : systeem.sleutel
  const schemeId = `conceptscheme:${sleutel}_type`
  const alle = conceptenVanScheme(result, schemeId)
  const zichtbaar = alle.filter((concept) => concept.isOnzichtbaar !== true)
  const zichtbaarById = new Map(zichtbaar.map((concept) => [concept.id, concept]))

  const kinderenVan = new Map<string, Concept[]>()
  const wortels: Concept[] = []

  for (const concept of zichtbaar) {
    const ouder = concept.broader && zichtbaarById.has(concept.broader) ? concept.broader : undefined
    if (!ouder) {
      wortels.push(concept)
      continue
    }
    if (!kinderenVan.has(ouder)) kinderenVan.set(ouder, [])
    kinderenVan.get(ouder)!.push(concept)
  }

  const resultaat: StructuurType[] = []
  const bezocht = new Set<string>()

  /**
   * Depth-first walk so a subtype is always listed directly under its parent.
   * @param concept - The concept to add.
   * @param diepte - Its indentation level.
   */
  const voegToe = (concept: Concept, diepte: number): void => {
    if (bezocht.has(concept.id)) return
    bezocht.add(concept.id)
    resultaat.push({
      id: concept.id,
      systeem: sleutel,
      label: concept.prefLabel ?? concept.id,
      definitie: concept.definition,
      broader: concept.broader,
      diepte,
      isMeetbaar: concept.isMeetbaar === true,
    })
    for (const kind of kinderenVan.get(concept.id) ?? []) voegToe(kind, diepte + 1)
  }

  for (const wortel of wortels) voegToe(wortel, 0)

  // Defensive: a broken broader-cycle should never hide a type.
  for (const concept of zichtbaar) voegToe(concept, 0)

  return resultaat
}

/**
 * Converts a concept to an `Eigenschap`.
 * @param concept - The eigenschap concept.
 * @param kinderen - Its composite children, in source order.
 * @returns The eigenschap view.
 */
function naarEigenschap(concept: Concept, kinderen: Eigenschap[]): Eigenschap {
  return {
    id: concept.id,
    label: concept.prefLabel ?? concept.id,
    definitie: concept.definition,
    verplicht: concept.isVerplicht === true,
    meervoudig: concept.isMeervoudig === true,
    dataType: concept.relevantDataType,
    codeList: concept.relevantCodeList?.[0],
    unit: concept.relevantUnit?.[0],
    relatie: concept.relation,
    predicaat: concept.relevantProperty,
    multiselect: concept.isMultiselect === true,
    kinderen,
  }
}

/**
 * The scope of an eigenschap: the types (or `riepr:*` refs) it applies to.
 * For a composite the scope is the union of the effective scopes of its
 * children; a child without its own `relevantRiepr` inherits the parent's.
 * @param concept - The eigenschap concept.
 * @param kinderen - Its composite children as concepts.
 * @param erfenis - The scope inherited from the parent composite.
 * @returns The list of refs (possibly empty).
 */
function scopeVan(concept: Concept, kinderen: Concept[], erfenis: string[] = []): string[] {
  const eigen = concept.relevantRiepr?.length ? concept.relevantRiepr : erfenis

  if (kinderen.length === 0) return eigen

  const union = new Set<string>()
  for (const kind of kinderen) {
    for (const ref of scopeVan(kind, [], eigen)) union.add(ref)
  }
  return [...union]
}

/**
 * Whether a scope applies to a type.
 * @param scope - The scope refs.
 * @param typeId - The selected type.
 * @param ancestors - Its ancestors (from `getAncestors`).
 * @returns True when one ref is the type itself or one of its ancestors.
 */
function scopeBevatType(scope: string[], typeId: string, ancestors: string[]): boolean {
  const kandidaten = new Set([typeId, ...ancestors])
  return scope.some((ref) => kandidaten.has(ref))
}

/**
 * The root-eigenschappen that apply to a type, with their composite children.
 * Order = CSV order.
 * @param result - The parsed codelist.
 * @param systeem - The system key.
 * @param typeId - The selected type.
 * @returns The eigenschappen (empty when the type has none).
 */
export function getEigenschappen(
  result: CodelistResult,
  systeem: SysteemSleutel | Systeem,
  typeId: string,
): Eigenschap[] {
  const sleutel = typeof systeem === 'string' ? systeem : systeem.sleutel
  const schemeId = `conceptscheme:${sleutel}_eigenschappen`
  const alle = conceptenVanScheme(result, schemeId)
  const alleById = new Map(alle.map((concept) => [concept.id, concept]))

  const kinderenVan = new Map<string, Concept[]>()
  const wortels: Concept[] = []

  for (const concept of alle) {
    const ouder = concept.broaderPartitive?.find((parent) => alleById.has(parent))
    if (ouder) {
      if (!kinderenVan.has(ouder)) kinderenVan.set(ouder, [])
      kinderenVan.get(ouder)!.push(concept)
    } else {
      wortels.push(concept)
    }
  }

  const ancestors = getAncestors(result, typeId)

  /**
   * Builds one eigenschap and its children recursively.
   * @param concept - The eigenschap concept.
   * @returns The eigenschap view.
   */
  const bouw = (concept: Concept): Eigenschap => {
    const kinderen = (kinderenVan.get(concept.id) ?? []).map((kind) => bouw(kind))
    return naarEigenschap(concept, kinderen)
  }

  return wortels
    .filter((concept) => {
      const kinderen = kinderenVan.get(concept.id) ?? []
      return scopeBevatType(scopeVan(concept, kinderen), typeId, ancestors)
    })
    .map((concept) => bouw(concept))
}

/**
 * The options of a selection list referenced by `relevantCodeList`.
 *
 * - `conceptscheme:*` — an inline list from the RIE-IEPR codelist (source order);
 * - `collectie:*` — a CSOR collection (alphabetical, labels from `csor.json`);
 * - anything else — an externally published list that this POC cannot resolve,
 *   so no options are returned and the field falls back to free text.
 * @param result - The parsed codelist.
 * @param codeListId - The value of `relevantCodeList`.
 * @param csor - The CSOR resolver.
 * @returns The options (possibly empty).
 */
export function getSelectieOpties(
  result: CodelistResult,
  codeListId: string,
  csor: CsorService = new CsorService(),
): SelectieOptie[] {
  if (codeListId.startsWith('conceptscheme:')) {
    return conceptenVanScheme(result, codeListId).map((concept) => ({
      id: concept.id,
      label: concept.prefLabel ?? concept.id,
      definitie: concept.definition,
    }))
  }

  if (codeListId.startsWith('collectie:')) {
    return csor.resolveCollection(collectieLeden(result, codeListId))
  }

  return []
}

/**
 * The member ids of a collection: CSV order first, the generated JSON-LD as fallback.
 * @param result - The parsed codelist.
 * @param collectieId - The collection id.
 * @returns The member ids.
 */
function collectieLeden(result: CodelistResult, collectieId: string): string[] {
  return CSV_VOLGORDE.collections[collectieId] ?? result.collections.get(collectieId) ?? []
}

/**
 * The units of a `relevantUnit`, ready for a fixed suffix or a selector.
 * @param unitId - A single unit CURIE or a `collectie:*` of units.
 * @param result - The parsed codelist.
 * @param csor - The CSOR resolver.
 * @returns One option per unit (empty when `unitId` is undefined).
 */
export function getEenheden(
  unitId: string | undefined,
  result?: CodelistResult,
  csor: CsorService = new CsorService(),
): SelectieOptie[] {
  if (!unitId) return []

  const ids = unitId.startsWith('collectie:')
    ? (result ? collectieLeden(result, unitId) : (CSV_VOLGORDE.collections[unitId] ?? []))
    : [unitId]

  return csor.resolveOptions(ids)
}
